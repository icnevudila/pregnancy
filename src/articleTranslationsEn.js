/**
 * Returns localized article fields based on lang
 */
export function getLocalizedArticle(article, lang = 'tr') {
  if (!article) return article;
  if (lang !== 'en') return article;

  const translation = articleTranslationsEn[article.id];
  if (!translation) return article;

  return {
    ...article,
    title: translation.title || article.title,
    titleEn: translation.title || article.titleEn,
    subtitle: translation.subtitle || article.subtitle,
    subtitleEn: translation.subtitle || article.subtitleEn,
    categoryName: translation.categoryName || article.categoryName,
    doctor: translation.doctor || article.doctor,
    keyPoints: translation.keyPoints || article.keyPoints,
  };
}
